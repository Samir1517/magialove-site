"use client";

import { useSearchParams } from "next/navigation";
import Link from "next/link";
import styles from "./content.module.css";

/**
 * «Вернуться к вашему расчёту» на статейной странице.
 *
 * Найдено проходом по живому сайту. Человек считает совместимость, видит свой
 * аркан, уходит читать разбор — и обратно к результату ему нечем: все ссылки
 * на странице аркана ведут на пустой калькулятор, то есть вводить обе даты
 * заново. Кнопка «назад» в браузере спасает один раз, но не после двух-трёх
 * переходов по связям между арканами, а именно туда мы читателя и зовём.
 *
 * Момент важный: человек уходит читать ровно тогда, когда он максимально
 * вовлечён. Терять его на возврате — худшее время из возможных, и в поиске
 * это читается как неудачная сессия.
 *
 * Как работает: ссылки из расчёта несут параметры (даты и имена), компонент их
 * подхватывает и собирает обратный адрес. Если параметров нет — человек пришёл
 * из поиска, а не из расчёта, — не показываем ничего.
 *
 * SEO-риска нет: варианты адреса с параметрами существуют только на клиентской
 * странице результата, которая не индексируется, а на самих статьях прописан
 * canonical на чистый адрес.
 */
export function BackToCalculation({ resultHref }: { resultHref: string }) {
  const params = useSearchParams();
  const a = params.get("a");
  const b = params.get("b");
  if (!a || !b) return null;

  const nameA = params.get("na")?.trim();
  const nameB = params.get("nb")?.trim();
  // Имена приходят из формы в именительном падеже и склонению не поддаются
  // («по Анна и Максим»), поэтому ставим их после двоеточия, а не в оборот.
  const whose = nameA && nameB ? `: ${nameA} и ${nameB}` : "";

  return (
    <Link href={`${resultHref}?${params.toString()}`} className={styles.backToResult}>
      ← Вернуться к вашему расчёту{whose}
    </Link>
  );
}
