/**
 * Двенадцать домов (бхав) — бытовым языком.
 *
 * На карте человек видит «7-й дом» и не понимает ничего: цифра в углу клетки
 * не значит для него ровно ничего. Поэтому у каждого дома здесь два поля:
 * короткое название, по которому его узнают, и фраза о том, что он значит в
 * жизни — без санскрита и без астрологического жаргона.
 *
 * Значения домов — общее достояние традиции, они одинаковы во всех школах и
 * повторены в любом учебнике. Формулировки наши: мы переводим их на язык
 * женщины 25-45, которая читает про свою пару, а не изучает Джйотиш.
 *
 * Акцент сознательно смещён к отношениям — это сервис про совместимость. Но
 * дом не сводится к одной теме, поэтому вторым слоем даём и его общий смысл.
 */
export interface Bhava {
  /** Как дом зовут в традиции — коротко и узнаваемо. */
  title: string;
  /** Что он значит в обычной жизни. */
  meaning: string;
}

