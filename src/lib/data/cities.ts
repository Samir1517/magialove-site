/** Поиск по подстроке: сначала «начинается с», потом «содержит», без учёта ё/е и регистра. */
export function searchCities(query: string, limit = 8): City[] {
  const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е");
  const q = norm(query.trim());
  if (q.length < 2) return [];
  const starts: City[] = [];
  const contains: City[] = [];
  for (const c of CITIES) {
    const n = norm(c.name);
    if (n.startsWith(q)) starts.push(c);
    else if (n.includes(q)) contains.push(c);
    if (starts.length >= limit) break;
  }
  return [...starts, ...contains].slice(0, limit);
}

/** Для отображения выбранного по умолчанию/сохранённого пояса как города. */
export function findCityByTz(tz: string): City | null {
  return CITIES.find((c) => c.tz === tz) ?? null;
}
