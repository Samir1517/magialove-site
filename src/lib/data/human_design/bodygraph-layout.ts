/**
 * Середина канала. В стандартной карте каналы идут ПРЯМЫМИ отрезками, включая
 * длинный 26–44 и «интеграционный» пучок 10/20/34/57 — они проходят вплотную к
 * G-центру, и именно так карта и выглядит у всех вендоров. Собственных изломов
 * не добавляем: это первое, по чему самодельный бодиграф видно невооружённым
 * глазом.
 */
export function channelMid(_key: string, a: [number, number], b: [number, number]): [number, number] {
  return [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];
}
