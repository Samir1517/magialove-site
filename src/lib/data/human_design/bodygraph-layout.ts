/**
 * Путь канала, разбитый на две половины — по одной на каждые ворота. Половины
 * красятся отдельно: только так в карте видно висящие ворота (одна половина
 * закрашена, вторая белая) и разные активации Личности и Дизайна на одном
 * канале. Канал 26–44 остаётся прямым и пересекает вертикальные каналы
 * G↔Сакрал — это единственное узаконенное пересечение в карте, «спрямлять»
 * или обводить его нельзя.
 */
export function channelHalves(
  key: string,
  gateFirst: number,
  gateSecond: number
): { first: Point[]; second: Point[] } {
  const bent = INTEGRATION[key];
  if (bent) {
    return bent.from === gateFirst
      ? { first: bent.first, second: bent.second }
      : { first: bent.second, second: bent.first };
  }
  const p1 = GATE_POS[gateFirst];
  const p2 = GATE_POS[gateSecond];
  const mid: Point = [(p1[0] + p2[0]) / 2, (p1[1] + p2[1]) / 2];
  return { first: [p1, mid], second: [mid, p2] };
}
