/**
 * Середина канала. Обычно это просто центр отрезка, но у трёх каналов прямая
 * прошла бы сквозь чужой центр, поэтому середина сдвинута — ровно так же
 * изгибы сделаны в классической карте.
 */
const MID_OVERRIDE: Record<string, [number, number]> = {
  // 26-44 пересекает всю карту: ведём его под G-центром, а не сквозь него.
  "26-44": [152, 388],
  // 10-57 и 34-57 огибают сакральный центр слева.
  "10-57": [102, 350],
  "34-57": [104, 400],
  // 20-57: от горла к селезёнке мимо G-центра.
  "20-57": [100, 300],
  // 20-34 идёт вдоль левого края мимо G-центра.
  "20-34": [106, 316],
};

export function channelMid(key: string, a: [number, number], b: [number, number]): [number, number] {
  const override = MID_OVERRIDE[key];
  if (override) return override;
  return [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];
}
