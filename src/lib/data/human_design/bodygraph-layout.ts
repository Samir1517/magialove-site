/**
 * Геометрия классического бодиграфа (Rave Body Graph).
 *
 * Форму менять нельзя: практики Дизайна человека узнают карту с одного
 * взгляда, и любая «улучшенная» схема ломает узнавание. Поэтому здесь
 * воспроизведена стандартная топология — девять центров канонических форм и
 * все 64 ворот на их периметрах, каждые напротив своего партнёра по каналу.
 *
 * Канал рисуется ДВУМЯ половинами: ворота → середина → ворота. Это не
 * украшение, а суть карты: половина принадлежит одному концу канала, и в
 * классической карте каждая половина красится отдельно (Личность/Дизайн).
 * Та же механика позволяет в парной карте покрасить половины по партнёрам и
 * сразу увидеть, кто какие ворота приносит.
 *
 * Система координат: viewBox 320×620.
 */

