/**
 * Относительная популярность имён — используется, чтобы решить, какие из 64
 * пар (8 мужских × 8 женских, пилотный список) достаточно частотны для
 * публикации отдельной страницы.
 *
 * ЧЕСТНО О МЕТОДОЛОГИИ: прямого доступа к Яндекс.Wordstat нет — сервис не
 * отдаёт цифры без входа в аккаунт (проверено WebFetch на wordstat.yandex.ru:
 * страница показывает только форму поиска, ни одного числа без авторизации).
 * Это тот же принцип, что уже использован в исходном `semantika/_generator.py`
 * для остальных 377 запросов семантического ядра: "частотности — экспертная
 * оценка... без доступа к Wordstat/Key Collector. Перед разработкой
 * контент-плана проверить точные значения в Wordstat".
 *
 * Вместо точных цифр — трёхуровневая оценка, построенная на реальных
 * источниках популярности русских имён (не выдумана):
 *   - Яндекс, исследование 2012 г. (35 млн аккаунтов соцсетей и блогов):
 *     лидеры по всей популяции — Александр, Елена, Сергей, Дмитрий, Ольга.
 *     https://yandex.ru/company/researches/2012/ya_names_2012
 *   - Данные по поколениям (tanoshi-club.com, со ссылкой на статистику ЗАГС):
 *     миллениалы (1981–1996, сейчас 30–40 лет — основная аудитория сервиса)
 *     чаще всего называют мальчиков Артём/Максим/Иван/Кирилл/Никита,
 *     девочек Анастасия/Екатерина/Дарья/Мария/Виктория; поколение X
 *     (1965–1980) — мальчиков Сергей/Андрей/Алексей/Дмитрий/Олег,
 *     девочек Елена/Ольга/Наталья/Ирина/Светлана.
 * Все 8 мужских и 8 женских имён исходного пилотного списка входят в топ-5
 * хотя бы одного из этих двух поколений или в общероссийский топ Яндекса —
 * то есть весь список уже достаточно частотный, урезать его не потребовалось.
 * tier 3 (высшая) — имя в обоих источниках; tier 2 — в одном; tier 1 — только
 * в исходном пилотном списке.
 */

export const NAME_TIER: Record<string, 1 | 2 | 3> = {
  // мужские
  Александр: 3, // Яндекс топ-1 общий + топ Gen Z
  Дмитрий: 3, // Яндекс топ-4 общий + топ Gen X
  Андрей: 2, // топ Gen X
  Михаил: 2, // топ Gen Z / текущих новорождённых
  Максим: 2, // топ миллениалов
  Иван: 2, // топ миллениалов
  Артём: 2, // топ миллениалов и Gen Z
  Никита: 2, // топ миллениалов
  // женские
  Елена: 3, // Яндекс топ-2 общий + топ Gen X
  Ольга: 3, // Яндекс топ-5 общий + топ Gen X
  Анастасия: 2, // топ миллениалов
  Мария: 2, // топ миллениалов
  Екатерина: 2, // топ миллениалов
  Дарья: 2, // топ миллениалов
  Виктория: 2, // топ миллениалов
  Анна: 1, // устойчиво распространено, вне явного топа источников выше
};

/** Оценка относительной частоты пары — только для сортировки/приоритезации,
 *  не точное число. Выше — вероятно чаще ищут. */
export function pairPriority(m: string, f: string): number {
  return (NAME_TIER[m] ?? 1) + (NAME_TIER[f] ?? 1);
}

/**
 * Транслитерация в URL слаги — сознательное отступление от исходного плана
 * семантического ядра (там слаги были кириллицей: "александр-i-анастасия").
 * Причина: `next build` с `output: "export"` молча подменяет страницу на
 * страницу-заглушку ошибки для юникод-сегментов динамического роута — сборка
 * завершается без ошибки в консоли, но реальный контент не попадает в HTML
 * (обнаружено при проверке собранного `out/`, не в dev-режиме). Латинский
 * слаг снимает проблему полностью и заодно надёжнее для сторонних тулов.
 */
const TRANSLIT: Record<string, string> = {
  Александр: "aleksandr",
  Дмитрий: "dmitriy",
  Максим: "maksim",
  Иван: "ivan",
  Артём: "artem",
  Никита: "nikita",
  Михаил: "mihail",
  Андрей: "andrey",
  Анастасия: "anastasiya",
  Мария: "mariya",
  Анна: "anna",
  Елена: "elena",
  Ольга: "olga",
  Екатерина: "ekaterina",
  Дарья: "darya",
  Виктория: "viktoriya",
};

export function nameSlug(name: string): string {
  return TRANSLIT[name] ?? name.toLowerCase();
}

