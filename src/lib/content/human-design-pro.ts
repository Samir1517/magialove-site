/**
 * Тексты профессионального разбора: обусловленность по девяти центрам.
 *
 * Что здесь и зачем. Открытый центр — место, где человек принимает чужую
 * энергию и усиливает её как свою. Когда у одного центр открыт, а у второго
 * включён, рядом друг с другом это работает каждый день. Блок отвечает на
 * вопрос «в чём именно рядом с ним я перестаю быть собой» — и на обратный,
 * «а что я делаю с ним такого, чего сама не замечаю».
 *
 * ПОЧЕМУ ДВЕ СТОРОНЫ, А НЕ ОДНА. Первая версия описывала только случай «центр
 * открыт у тебя». Блок показывает обе стороны, и на обратной получалось «рядом
 * с ним тебе так спокойно» — про партнёра, у которого центр открыт. То есть
 * партнёра называли «ты», а читателя «ним». Поэтому у каждого центра два
 * набора: `you` — открыт у читателя, `partner` — открыт у партнёра.
 *
 * РОД. Родовые окончания размечены (см. `content/gender.ts`): `{т:…}` про
 * читателя, `{п:…}` про партнёра, порядок всегда мужской-женский. Два комплекта
 * текстов вместо разметки неизбежно разъехались бы, а забытое место здесь видно
 * прямо в строке — и его же ловит `findBareGendered` в смоук-тесте.
 *
 * В общих формулировках («у кого этот центр включён, тот…») рода нет намеренно:
 * они про механику, а не про конкретного человека. По той же причине в них
 * нигде не стоит голое «он» про сам центр — иначе проверка утонула бы в ложных
 * срабатываниях.
 *
 * Как написано. По стандарту, утверждённому на образце
 * (`professionalnye-raschety/dizajn-cheloveka/obrazcy/blok-obuslovlennost.md`):
 *
 *   1. Никаких терминов без расшифровки — `organ` объясняет, что делает центр,
 *      бытовыми словами и до того, как прозвучит название.
 *   2. Узнаваемая сцена вместо свойства. «Ты восприимчива к чужим убеждениям»
 *      не с чем сверить; «ты замолкаешь, пока не придумаешь, как сказать»
 *      либо было, либо нет.
 *   3. Свет и тень — одно обстоятельство с двух сторон, а не два списка.
 *   4. `fixed` и `changeable` разделяют навсегда и последствие. Это главный
 *      ответ на вопрос, с которым читатель пришёл: изменится ли партнёр.
 *
 * Чего здесь НЕТ намеренно: конкретных ворот. Они подставляются на месте, из
 * расчёта, и именно они делают абзац непереиспользуемым для другой пары.
 * Эти описания — рама, а не весь текст.
 */

import type { CenterKey } from "@/lib/engines/human-design-tables";

export interface ConditioningSide {
  /** Узнаваемая сцена: то, что либо было, либо нет. */
  scene: string;
  /** Светлая сторона ровно того же обстоятельства. */
  light: string;
  /** Что здесь не изменится никогда. */
  fixed: string;
  /** Что является последствием и лечится — обязательно с конкретным действием. */
  changeable: string;
  /** Что значат собственные активации в открытом центре: за что человек держится. */
  anchor: string;
}

export interface ConditioningText {
  /** Короткая подпись блока: чего касается влияние. */
  topic: string;
  /** Что делает этот центр — бытовым языком, до всякой терминологии. */
  organ: string;
  /** Центр открыт у читателя: партнёр влияет на него. */
  you: ConditioningSide;
  /** Центр открыт у партнёра: читатель влияет на него. */
  partner: ConditioningSide;
}

