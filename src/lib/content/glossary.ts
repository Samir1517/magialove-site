/**
 * Короткие объяснения терминов, которые иначе отсекают читателя от расчёта.
 *
 * Человек приходит узнать про свою пару, а получает «Мангал доша от Чандра-
 * лагны». Слово, значения которого не знаешь, работает не как знание, а как
 * забор: либо человек уходит, либо кивает, не поняв. Поэтому у каждого такого
 * термина на странице стоит вопросик, а здесь лежит его расшифровка.
 *
 * Правила текста:
 * — `what` отвечает «что это вообще», человеческими словами, без санскрита
 *   внутри объяснения санскрита;
 * — `why` отвечает «а мне это о чём», то есть что показывает расчёт по этому
 *   понятию в паре;
 * — никакого фатализма: у трудного показателя называем и то, что он даёт.
 */
export interface GlossaryEntry {
  /** Заголовок подсказки — как термин звучит на странице. */
  title: string;
  /** Что это такое. */
  what: string;
  /** Что показывает расчёт по этому понятию. */
  why: string;
  /**
   * Адрес разбора этого понятия, если он у нас есть отдельной страницей.
   * Подсказка тогда показывает ссылку «Читать подробнее».
   *
   * Заполнять только там, где страница реально существует: подсказка обязана
   * оставаться честной, а несуществующие разделы под термин не выдумываются.
   */
  href?: string;
  /** Анкор ссылки — с ключевыми словами, а не «подробнее». */
  hrefLabel?: string;
}

