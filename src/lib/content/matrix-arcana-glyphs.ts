/**
 * Практика глифов — вход в состояние аркана вдвоём.
 *
 * Откуда подход. У Владимира Шмакова («Священная книга Тота», 1916) аркан
 * понимается не как предсказание и не как «значение карты», а как СОСТОЯНИЕ,
 * в которое входят: карта при таком чтении — не картинка, а собрание
 * символов-глифов, каждый со своим внутренним тоном. Осваивают их по
 * отдельности, а потом берут все разом, как аккорд.
 *
 * Что здесь наше. Сам перечень символов карты — общеизвестная фактура
 * традиции. Угол другой: у Шмакова и в любом разборе для одного человека
 * глиф — это личное состояние. Здесь каждый глиф прочитан как то, что пара
 * может включить ВДВОЁМ, и потому все формулировки написаны заново под союз.
 * Ни одно предложение не перенесено из источников.
 *
 * Правило то же, что и во всех текстах проекта: у состояния названа не только
 * светлая сторона. Аркан, в который вошли вдвоём, усиливает и то и другое.
 *
 * Нумерация матричная: 8 — Справедливость, 11 — Сила, 22 — Шут.
 */

export interface Glyph {
  /** Символ на карте — общеизвестная фактура традиции. */
  symbol: string;
  /** Что этот символ означает для двоих: состояние, которое можно включить вместе. */
  text: string;
}

