/**
 * Подстановка родовых окончаний в тексты разбора.
 *
 * Зачем. Пол на расчёт не влияет ни в одной из четырёх систем — и в Джйотише
 * тоже: у Парашары супруг читается от Венеры у обоих полов. Но на текст влияет,
 * и сильно: «он бодр наравне с тобой» про женщину читается как ошибка.
 *
 * Почему разметка, а не два комплекта текстов. Два комплекта неизбежно
 * разъезжаются: правку вносят в один, про второй забывают, и проверить это
 * ничем нельзя. Здесь текст один, а вариантов два, и забытое место видно
 * глазами прямо в строке.
 *
 * Разметка. Порядок всегда мужской, потом женский; любая половина может быть
 * пустой:
 *
 *   {п:Он|Она} бодр{п:|а} наравне с тобой — про партнёра
 *   раньше, чем ты {т:сам|сама} заметишь — про читателя
 *
 * Две метки нужны потому, что в одном абзаце встречаются оба: текст обращается
 * к читателю на «ты» и одновременно рассказывает про партнёра.
 */

export type Sex = "м" | "ж";

/** Читатель и партнёр: чей род подставлять в какую метку. */
export interface GenderContext {
  /** Пол того, к кому обращён текст, — метка `{т:…}`. */
  self: Sex;
  /** Пол второго человека — метка `{п:…}`. */
  other: Sex;
}

const MARKUP = /\{([тп]):([^{}|]*)\|([^{}|]*)\}/g;

/**
 * Разворачивает разметку под конкретную пару.
 *
 * Неизвестные метки не трогаются: лучше оставить в тексте видимую фигурную
 * скобку, которую заметят при вычитке, чем молча выбросить слово.
 */
export function applyGender(text: string, ctx: GenderContext): string {
  return text.replace(MARKUP, (whole, mark: string, masculine: string, feminine: string) => {
    const sex = mark === "т" ? ctx.self : mark === "п" ? ctx.other : null;
    if (sex === null) return whole;
    return sex === "м" ? masculine : feminine;
  });
}

/**
 * Слова, которые обязаны стоять в разметке. Ловят самую частую ошибку —
 * забытое голое «он» или «она» про человека.
 *
 * Список намеренно узкий: сюда входит только то, что в текстах разбора всегда
 * относится к человеку. Слова вроде «его» и «её» не годятся — они с той же
 * частотой указывают на вопрос, страх или центр, и проверка утонула бы в ложных
 * срабатываниях.
 */
const BARE_GENDERED = /\b(он|она|сам|сама|него|неё|нее)\b/gi;

/**
 * Ищет родовые слова, оставшиеся вне разметки.
 *
 * Работает по тексту, из которого разметка уже вырезана целиком, — иначе
 * находились бы слова внутри `{п:он|она}`, то есть ровно те, что уже учтены.
 */
export function findBareGendered(text: string): string[] {
  const stripped = text.replace(MARKUP, "");
  return [...stripped.matchAll(BARE_GENDERED)].map((m) => m[0]);
}
