/**
 * Астрологическое соответствие каждого из 22 арканов — знак зодиака, планета
 * или стихия.
 *
 * Откуда факт. Привязка 22 арканов к 12 знакам, 7 планетам и 3 стихиям — это
 * классическая система соответствий герметической традиции (те самые 22 пути
 * между сефирот), общеизвестная и воспроизведённая в десятках источников.
 * Сам факт соответствия мы не изобретаем и не присваиваем.
 *
 * Что здесь наше. Угол: что это соответствие значит для ПАРЫ, а не для одного
 * человека с картой в руках. И связка со своими же страницами — знак зодиака
 * у нас разобран отдельно, планета управляет своими знаками, стихия объединяет
 * три знака. Ссылки строятся из этих данных автоматически (см. ArcanumAstro.tsx),
 * поэтому руками их прописывать не нужно и рассинхронизироваться нечему.
 *
 * Нумерация наша, матричная: 8 — Справедливость, 11 — Сила, 22 — Шут.
 * В колодах уэйтовской традиции 8 и 11 стоят наоборот, поэтому соответствия
 * сверялись по ИМЕНИ аркана, а не по номеру.
 */

export type AstroKind = "sign" | "planet" | "element";

export interface ArcanumAstro {
  kind: AstroKind;
  /** Знак, планета или стихия — как принято называть в традиции. */
  value: string;
  /** Что это соответствие даёт паре. Свет и тень, как и везде в текстах. */
  text: string;
}

/**
 * Обратный поиск: какому аркану соответствует знак зодиака.
 *
 * Нужен, чтобы мост между разделами работал в обе стороны. Двенадцати знакам
 * отвечают двенадцать арканов (остальным десяти достались планеты и стихии),
 * и страницы зодиака — самый большой кластер сайта — получают отсюда содержательный
 * повод сослаться на разбор аркана.
 */
export function arcanumOfSign(signName: string): number | null {
  for (const [n, a] of Object.entries(ARCANUM_ASTRO)) {
    if (a.kind === "sign" && a.value === signName) return Number(n);
  }
  return null;
}

