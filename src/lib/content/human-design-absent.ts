/**
 * Блок «чего в вашей паре нет».
 *
 * Самый честный и самый редкий блок разбора. Все продают «что у вас есть» —
 * никто не продаёт «на что не надо тратить десять лет».
 *
 * Механика. Канал состоит из двух ворот. Если ни у одного из двоих нет ни той,
 * ни другой половины, темы в паре нет как материала: она не появится ни от
 * работы над отношениями, ни от времени, ни от желания. Если есть только одна
 * половина — тема звучит, но замкнуть её вдвоём нельзя, ответ придёт только
 * извне.
 *
 * ОТКУДА ГЛАВНАЯ ОПАСНОСТЬ ЭТОГО БЛОКА. Отсутствующих каналов у любой пары
 * большинство: их всего 36, а закрывается обычно меньше десятка. Подать это
 * без калибровки — значит напугать человека списком из двадцати семи пунктов
 * «чего у вас нет». Поэтому `norm` обязателен и идёт раньше самого списка.
 *
 * Тексты самих каналов не дублируются: берутся из `CHANNEL_PAIR.appears` —
 * там уже описано, что канал даёт, и для отсутствующей темы этого достаточно.
 */

