export type CountBand = "deficit" | "norm" | "excess";

export function countBand(count: number): CountBand {
  if (count === 0) return "deficit";
  if (count <= 2) return "norm";
  return "excess";
}

export const COUNT_BAND_LABEL: Record<CountBand, string> = {
  deficit: "не заполнено",
  norm: "норма",
  excess: "избыток",
};

export function digitReading(digit: number, count: number): string {
  const m = DIGIT_MEANINGS[digit];
  const band = countBand(count);
  return band === "deficit" ? m.deficit : band === "norm" ? m.norm : m.excess;
}
