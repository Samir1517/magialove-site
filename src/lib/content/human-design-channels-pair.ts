/**
 * Что канал делает в паре: тексты для блоков «почему тянет» и «что вы
 * достраиваете друг в друге».
 *
 * Механика. Канал состоит из двух ворот. Если у человека активирована только
 * половина, канал висит незамкнутым — и всю жизнь тянет к тем, у кого есть
 * вторая. Встретились двое, у каждого своя половина, — канал замкнулся, и между
 * ними появилось то, чего нет ни у одного поодиночке. Это и есть механизм
 * притяжения в чистом виде, разложенный по деталям.
 *
 * Отдельно про мост: если замкнувшийся канал соединяет два несвязанных куска
 * карты одного из двоих, он не просто добавляет тему — он сшивает человека. У
 * такого канала теневая сторона сильнее, и `shadow` это учитывает.
 *
 * ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО: обещания «это твой человек». По первоисточнику
 * притяжение подвешенных ворот — компульсия, крючок, а не доказательство
 * правильности выбора. Мы объясняем механику, а не благословляем пару.
 *
 * Тексты пишутся не из структуры канала, а из его собственного смысла. Вывод
 * смысла из общей схемы уже был ошибкой один раз — так родились и были удалены
 * 384 пояснения к линиям (см. docs/dizajn-cheloveka.md, раздел 5). Здесь у
 * каждого канала свой текст.
 *
 * Род: где не обойтись, стоит разметка из `content/gender.ts`. Но большинство
 * фраз здесь про «вас двоих», и рода в них нет вовсе — это удобно и намеренно.
 */

