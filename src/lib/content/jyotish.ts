/** Традиционные пороги суммы Гуна-милан (из 36). */
export const GUNA_THRESHOLDS = [18, 24, 30];

export function gunaBandLabel(total: number): string {
  if (total >= 33) return "отличная по традиции";
  if (total >= 25) return "хорошая по традиции";
  if (total >= 18) return "приемлемая по традиции";
  return "низкая по традиции";
}
