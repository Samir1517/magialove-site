/** Индекс знака в круге, от Овна. */
function signIndex(s: ZodiacSign): number {
  return ZODIAC_SIGNS.findIndex((x) => x.key === s.key);
}

/** Аспект между знаками — угловое расстояние по кругу зодиака. */
export function aspectBetween(a: ZodiacSign, b: ZodiacSign): AspectInfo {
  const d = Math.abs(signIndex(a) - signIndex(b));
  const dist = Math.min(d, 12 - d);
  const key: AspectKey = (
    ["conjunction", "semisextile", "sextile", "square", "trine", "quincunx", "opposition"] as AspectKey[]
  )[dist];
  return { key, ...ASPECTS[key] };
}

/**
 * Полярность знака: нечётные по счёту знаки традиция называет активными
 * (ян, «мужскими»), чётные — воспринимающими (инь, «женскими»). К полу
 * человека это отношения не имеет — речь о способе действовать.
 */
export function polarity(s: ZodiacSign): "ян" | "инь" {
  return signIndex(s) % 2 === 0 ? "ян" : "инь";
}

/** Стихии, которые традиция считает питающими друг друга. */
const FRIENDLY: Record<Element, Element> = {
  fire: "air",
  air: "fire",
  earth: "water",
  water: "earth",
};

/**
 * Как аспект выглядит именно у этой пары.
 *
 * Общие тексты аспекта, стихии и креста зависят только от категории, поэтому
 * у пар с одинаковыми параметрами совпадали дословно: замер давал 69% общего
 * текста у «Лев и Овен» против «Лев и Стрелец». Этот абзац привязывает теорию
 * к конкретным знакам — через их управителей, кресты и даты, то есть через то,
 * что у двух пар не совпадает никогда.
 */
export function aspectInPair(a: ZodiacSign, b: ZodiacSign): string {
  const same = a.key === b.key;
  if (same) {
    return (
      `У пары из двух ${a.genitive} это выглядит так: оба родились в один и тот же отрезок года ` +
      `(${a.dateRange}), у обоих управитель ${a.ruler} и ${MODALITY_LABEL[a.modality].toLowerCase()} крест. ` +
      `Совпадает не только характер, но и способ реагировать на неожиданное — а значит, в трудной ситуации ` +
      `оба сделают один и тот же ход, верный он или нет.`
    );
  }
  const aRuler = mainRuler(a);
  const bRuler = mainRuler(b);
  return (
    `У ${a.genitive} и ${b.genitive} это выглядит конкретно так. ${a.name} ${verb(a, "рождается", "рождаются")} ${a.dateRange.toLowerCase()}, ` +
    `управитель ${aRuler}, крест ${MODALITY_LABEL[a.modality].toLowerCase()} — отсюда ${a.strength}. ` +
    `${b.name} — ${b.dateRange.toLowerCase()}, управитель ${bRuler}, крест ${MODALITY_LABEL[b.modality].toLowerCase()}, ` +
    `отсюда ${b.strength}. ` +
    (aRuler === bRuler
      ? `Управитель у знаков общий, и это редкость: спорят такие пары не о ценностях, а о способе их отстаивать.`
      : `Разные управители означают, что и заряжаются партнёры от разного — ${aRuler} и ${bRuler} требуют от человека несхожих вещей.`)
  );
}

/** Как сочетание стихий проявляется у этих двух знаков, а не у стихий вообще. */
export function elementsInPair(a: ZodiacSign, b: ZodiacSign): string {
  if (a.element === b.element) {
    return (
      `Оба знака принадлежат стихии ${ELEMENT_LABEL[a.element]}, но ведут себя в ней по-разному: ` +
      `${a.name} — ${MODALITY_LABEL[a.modality].toLowerCase()} знак этой стихии, ${b.name} — ` +
      `${MODALITY_LABEL[b.modality].toLowerCase()}. ` +
      (a.modality === b.modality
        ? `Здесь кресты совпали, и это усиливает сходство до предела.`
        : `Поэтому общая стихия не делает вас одинаковыми: один задаёт направление, другой распоряжается им иначе.`)
    );
  }
  return (
    `На практике разница стихий у этой пары читается так: ${a.strength} у ${a.genitive} растёт из ` +
    `${ELEMENT_LABEL[a.element].toLowerCase()}, а ${b.strength} у ${b.genitive} — из ` +
    `${ELEMENT_LABEL[b.element].toLowerCase()}. Ссоры почти никогда не идут про стихии напрямую: ` +
    `они идут про то, что ${a.shadow} и ${b.shadow} включаются в один и тот же момент.`
  );
}

/**
 * Кресты — но про конкретные знаки, а не про кресты вообще.
 *
 * Общая теория крестов даёт всего шесть текстов на 78 страниц, и это один из
 * самых крупных совпадающих кусков. Здесь то же самое сказано через имена,
 * управителей и сильные стороны обоих знаков — читателю полезнее, поисковику
 * не выглядит копией соседней страницы.
 */
export function modalitiesInPair(a: ZodiacSign, b: ZodiacSign): string {
  if (a.key === b.key) {
    return (
      `Оба ${a.genitive} несут ${MODALITY_LABEL[a.modality].toLowerCase()} крест: каждый ` +
      `${MODALITY_ROLE[a.modality][0]}. Когда в паре это делают двое сразу, ` +
      `${a.modality === "cardinal" ? "начатых дел становится больше, чем доведённых" : a.modality === "fixed" ? "любая перемена даётся паре тяжело — оба держат привычный уклад" : "решения переигрываются по кругу, и точку никто не ставит"}.`
    );
  }
  if (a.modality === b.modality) {
    return (
      `Крест у знаков один — ${MODALITY_LABEL[a.modality].toLowerCase()}: и ${a.name}, и ${b.name} ` +
      `${MODALITY_ROLE[a.modality][1]}. Совпадение здесь не помощь, а конкуренция: обоим нужна одна и та же роль в паре, ` +
      `и уступать её никто не научен. Помогает только явная договорённость, кто за что отвечает, — сама собой она не сложится.`
    );
  }
  return (
    `Кресты разные, и это заметная опора пары. ${a.name} ${modalityRole(a)}; ` +
    `${b.name} ${modalityRole(b)}. Функции не пересекаются, поэтому в быту вы не спорите за одну роль — ` +
    `${a.strength} у одного и ${b.strength} у другого дополняют друг друга, а не конкурируют.`
  );
}

export interface PairScore {
  total: number;
  parts: { label: string; value: number; max: number; why: string }[];
}

/**
 * Балл совместимости пары знаков — по четырём осям с явными весами.
 *
 * Честная оговорка, которая стоит и на странице: это наша арифметика поверх
 * классических правил, а не цифра из астрологической традиции — в ней баллов
 * нет вообще. Мы публикуем формулу целиком именно поэтому: читатель должен
 * видеть, из чего сложилось число, и не принимать его за приговор.
 */
export function pairScore(a: ZodiacSign, b: ZodiacSign): PairScore {
  const aspect = aspectBetween(a, b);

  const sameElement = a.element === b.element;
  const friendly = FRIENDLY[a.element] === b.element;
  const elementValue = sameElement ? 25 : friendly ? 22 : 13;
  const elementWhy = sameElement
    ? `одна стихия — ${ELEMENT_LABEL[a.element]}: общий язык и общий перекос сразу`
    : friendly
      ? `${ELEMENT_LABEL[a.element]} и ${ELEMENT_LABEL[b.element]} питают друг друга`
      : `${ELEMENT_LABEL[a.element]} и ${ELEMENT_LABEL[b.element]} живут в разном темпе`;

  const sameModality = a.modality === b.modality;
  const modalityValue = sameModality ? 12 : 20;
  const modalityWhy = sameModality
    ? "кресты совпадают: оба одинаково реагируют на перемены, уступать некому"
    : "кресты разные: один начинает, другой удерживает — роли делятся сами";

  const samePolarity = polarity(a) === polarity(b);
  const polarityValue = samePolarity ? 10 : 15;
  const polarityWhy = samePolarity
    ? `оба ${polarity(a)}: похожий способ действовать, меньше взаимной подстройки`
    : "разная полярность: один активнее предлагает, второй охотнее принимает";

  const parts = [
    { label: "Аспект", value: aspect.weight, max: 30, why: `${aspect.name} ${aspect.angle}` },
    { label: "Стихии", value: elementValue, max: 25, why: elementWhy },
    { label: "Кресты", value: modalityValue, max: 20, why: modalityWhy },
    { label: "Полярность", value: polarityValue, max: 15, why: polarityWhy },
  ];

  return { total: parts.reduce((s, p) => s + p.value, 0), parts };
}

