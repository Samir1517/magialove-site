/** Роль креста, согласованная с числом знака. */
function modalityRole(s: ZodiacSign): string {
  return MODALITY_ROLE[s.modality][isPluralSign(s) ? 1 : 0];
}

/** Первый (традиционный) управитель — из записей вида «Марс/Плутон». */
function mainRuler(s: ZodiacSign): string {
  return s.ruler.split("/")[0].trim();
}

export interface RulersText {
  heading: string;
  intro: string;
  light: string;
  shadow: string;
}

export function rulersText(a: ZodiacSign, b: ZodiacSign): RulersText | null {
  const pa = mainRuler(a);
  const pb = mainRuler(b);
  const ta = PLANET_TRAITS[pa];
  const tb = PLANET_TRAITS[pb];
  if (!ta || !tb) return null;

  const samePlanet = pa === pb;

  return {
    heading: samePlanet
      ? `Общий управитель пары: ${pa}`
      : `Управители пары: ${pa} и ${pb}`,
    intro: samePlanet
      ? `У обоих знаков один управитель — ${pa}, и отвечает он за ${ta.role}. Это редкий случай: партнёры устроены по одному чертежу, даже если внешне непохожи.`
      : `За ${a.genitive} стоит ${pa} — это ${ta.role}. За ${b.genitive} — ${pb}, то есть ${tb.role}. Планеты-управители объясняют не характер целиком, а то, чем каждый партнёр наполняет отношения.`,
    light: samePlanet
      ? `В пару оба приносят одно: ${ta.brings}. Совпадение здесь означает, что объяснять свои мотивы почти не приходится — партнёр узнаёт их как свои.`
      : `${a.name} ${verb(a, "приносит", "приносят")} ${ta.brings}. ${b.name} — ${tb.brings}. Это разные вклады, и они не конкурируют между собой.`,
    shadow: samePlanet
      ? `И цену оба платят одинаковую: ${ta.costs}. Уравновесить это в паре некому, поэтому черта проявляется в двойном размере.`
      : `Цена тоже разная: у ${a.genitive} это ${ta.costs}, у ${b.genitive} — ${tb.costs}. Чаще всего пара спотыкается там, где одна из этих черт встречается со второй.`,
  };
}

/**
 * Разборы по сферам: любовь, быт и брак, дружба, ссоры.
 *
 * Почему они здесь, а не общим текстом на аспект. Балл и аспект по построению
 * одинаковы у всех пар на одном расстоянии — все квадраты дают 52, все тригоны
 * 85. Если бы текст зависел только от них, двенадцать страниц квадратов были бы
 * дословно одинаковы, то есть ровно тем, за что кластер и выпал из индекса.
 * Поэтому каждый абзац собирается из сильной и теневой черты обоих знаков
 * (`strength` и `shadow` в ZODIAC_SIGNS), их управителей и дат — этого набора
 * нет больше ни у одной пары.
 *
 * Заголовок страницы обещает «в любви, браке и дружбе», а таких разделов на
 * ней не было вовсе — читатель приходил за одним, а получал теорию стихий.
 */
export interface SphereText {
  heading: string;
  light: string;
  shadow: string;
}

export function pairSpheres(a: ZodiacSign, b: ZodiacSign): SphereText[] {
  const aspect = aspectBetween(a, b);
  const same = a.key === b.key;
  const diffPolarity = polarity(a) !== polarity(b);
  const sameElement = a.element === b.element;
  const sameModality = a.modality === b.modality;

  const love: SphereText = {
    heading: same
      ? `${a.name} и ${a.name} в любви`
      : `${a.name} и ${b.name} в любви: что притягивает`,
    light: same
      ? `Влюблённость здесь узнаваемая: партнёр хочет того же и в том же темпе, и это ощущается как редкое облегчение — не надо объяснять, почему для тебя важно то, что важно. ${a.strength.charAt(0).toUpperCase() + a.strength.slice(1)} есть у обоих, и в хороший период она удваивается.`
      // Раньше сюда подставлялся aspect.light — тот же абзац, что стоит в блоке
      // аспекта выше. Один текст дважды на странице, поэтому здесь своя фраза.
      : `Притяжение держится на разнице: ${a.name} ${verb(a, "приносит", "приносят")} в отношения ${a.strength}, ${b.name} — ${b.strength}. ${
          sameElement
            ? `Стихия при этом общая — ${ELEMENT_LABEL[a.element].toLowerCase()}, поэтому темп у обоих совпадает и разгоняется пара быстро.`
            : `Стихии разные (${ELEMENT_LABEL[a.element].toLowerCase()} и ${ELEMENT_LABEL[b.element].toLowerCase()}), поэтому влюблённость обычно приходит через интерес к непохожему, а не через узнавание своего.`
        }`,
    shadow: same
      ? `Но и ${a.shadow} тоже у обоих. Когда эта черта включается одновременно, в паре не остаётся никого, кто посмотрел бы на ситуацию иначе — и мелкая размолвка разрастается, потому что оба реагируют одинаково.`
      : `Та же разница и ранит: ${a.name} ${verb(a, "срывается", "срываются")} в ${a.shadow}, ${b.name} — в ${b.shadow}. ${
          diffPolarity
            ? "Полярности разные, поэтому один в такой момент наступает, а второй замыкается — и каждому кажется, что виноват другой."
            : "Полярность у обоих одна, поэтому в трудный момент оба ведут себя одинаково: либо оба давят, либо оба молчат, и никто не делает шаг навстречу первым."
        }`,
  };

  const marriage: SphereText = {
    // «двух Овна» — ошибка (после «двух» нужен родительный множественного),
    // а форм множественного у нас в данных нет. Грамматична только связка
    // «два ${genitive}», её и используем во всех заголовках про один знак.
    heading: same
      ? `Быт и брак, когда в паре два ${a.genitive}`
      : `${a.name} и ${b.name} в браке и быту`,
    light: sameModality
      ? `В быту вы одинаково относитесь к переменам — ${a.modality === "cardinal" ? "оба готовы начинать новое и брать решение на себя" : a.modality === "fixed" ? "оба цените устойчивый уклад и держите слово" : "оба легко перестраиваетесь под обстоятельства"}. Договорившись один раз, вы не возвращаетесь к вопросу заново.`
      : `Быт — сильное место этой пары: ${a.name} ${modalityRole(a)}, ${b.name} ${modalityRole(b)}. Роли делятся сами собой, и спорить за одну и ту же функцию не приходится.`,
    shadow: sameModality
      ? `Обратная сторона одинакового креста: ${a.modality === "cardinal" ? "оба хотят решать, и вопрос «чьё решение главное» встроен в пару" : a.modality === "fixed" ? "если позиции разошлись, уступать не умеет никто — тупик держится долго" : "курс держать некому, и планы меняются быстрее, чем воплощаются"}.`
      : `Риск в другом: разделение ролей легко застывает. Через несколько лет пара обнаруживает, что один всегда решает, а второй всегда соглашается — и это уже не удобство, а перекос, из которого трудно выйти без разговора.`,
  };

  const friendship: SphereText = {
    heading: same ? `Дружба, когда в паре два ${a.genitive}` : `${a.name} и ${b.name} в дружбе`,
    light: sameElement
      ? `Как друзья вы сходитесь легче, чем как партнёры: общая стихия ${ELEMENT_LABEL[a.element].toLowerCase()} означает общий взгляд на то, что вообще стоит внимания. Дружбе это на пользу — общий перекос не мешает, потому что вести совместный быт не нужно. Держится такая дружба на том, что ценит каждый: ${a.strength} у ${a.genitive} и ${b.strength} у ${b.genitive}.`
      : `В дружбе разница стихий работает лучше, чем в любви: то, что в быту раздражает, на приятельской дистанции выглядит как интересный другой взгляд. ${a.name} ${verb(a, "приносит", "приносят")} в общение ${a.strength}, ${b.name} — ${b.strength}, и обменивать одно на другое проще, когда не надо делить холодильник.`,
    shadow: sameElement
      ? `Общий слепой участок остаётся: вдвоём вы будете подтверждать друг другу одни и те же выводы, и рядом не окажется никого, кто скажет «а если посмотреть иначе».`
      : `Долго держать такую дружбу без повода сложно: общих тем меньше, чем у похожих людей, и без общего дела или компании отношения тихо сходят на нет.`,
  };

  const conflict: SphereText = {
    heading: same ? `Из-за чего ссорятся два ${a.genitive}` : `Из-за чего ссорятся ${a.name} и ${b.name}`,
    light: diffPolarity
      ? `У пары есть встроенный выход из ссоры: полярности разные — ${a.name} ${polarity(a) === "ян" ? verb(a, "скорее настаивает", "скорее настаивают") : verb(a, "скорее принимает", "скорее принимают")}, ${b.name} ${polarity(b) === "ян" ? verb(b, "скорее настаивает", "скорее настаивают") : verb(b, "скорее принимает", "скорее принимают")}. Если это осознать, роли в конфликте не сталкиваются лоб в лоб.`
      : `Ссоритесь вы похоже: оба ${polarity(a)}, то есть оба ${polarity(a) === "ян" ? "идут на обострение, а не отступают" : "замолкают и ждут, пока другой начнёт"}. Это неожиданно помогает — реакция партнёра не кажется странной, потому что она своя же.`,
    // Винительный одушевлённых совпадает с родительным («задевает Льва»), а
    // вот «бьёт по Овна» требовало дательного, которого в данных нет — поэтому
    // обе части фразы переведены в переходную конструкцию.
    shadow: `Типичный сценарий такой: ${a.shadow} у ${a.genitive} задевает ${b.genitive}, а ${b.shadow} в ответ ранит ${a.genitive}. Круг замыкается, и спор перестаёт быть про исходный повод. Разорвать его получается только словами — назвать вслух не поступок, а то, что за ним стоит.`,
  };

  return [love, marriage, friendship, conflict];
}

/**
 * Словесная оценка балла — без обещаний и без приговоров.
 *
 * Без вводного оборота: он подставляется в месте использования. Когда оборот
 * сидел внутри, на странице выходило «По классическим правилам по классическим
 * правилам это одно из самых лёгких сочетаний».
 */
export function scoreVerdict(total: number): string {
  if (total >= 80) return "это одно из самых лёгких сочетаний";
  if (total >= 68) return "сочетание скорее лёгкое: опор больше, чем расхождений";
  if (total >= 56) return "смешанное сочетание: есть и общая опора, и встроенное трение";
  return "сочетание из непростых: общих опор мало, всё держится на договорённостях";
}
