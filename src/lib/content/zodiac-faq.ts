import { ELEMENT_LABEL, MODALITY_LABEL, type ZodiacSign } from "../data/zodiac";
import { aspectBetween, pairScore, polarity, scoreVerdict } from "./zodiac-synastry";
import type { FaqItem } from "@/components/content/HubDepth";

/**
 * Вопросы к странице пары знаков.
 *
 * Отвечают на то, что люди реально набирают: «подходят ли», «сколько
 * процентов», «кто главный», «стоит ли жениться». Раньше страница на такие
 * вопросы не отвечала вовсе — она объясняла теорию стихий, а спрашивают не о
 * ней. Ответы собираются из аспекта, стихий, крестов и качеств обоих знаков,
 * поэтому у каждой из 78 пар свои.
 */
export function zodiacPairFaq(a: ZodiacSign, b: ZodiacSign): FaqItem[] {
  const same = a.key === b.key;
  const aspect = aspectBetween(a, b);
  const score = pairScore(a, b);
  const pair = same ? `${a.name} и ${a.name}` : `${a.name} и ${b.name}`;

  const items: FaqItem[] = [];

  items.push({
    q: `Подходят ли ${pair} друг другу?`,
    a:
      `По классическим правилам западной астрологии ${scoreVerdict(score.total)}. ` +
      `Знаки стоят в аспекте «${aspect.name}» (${aspect.angle} по кругу зодиака), стихии — ` +
      `${ELEMENT_LABEL[a.element]} и ${ELEMENT_LABEL[b.element]}, кресты — ` +
      `${MODALITY_LABEL[a.modality].toLowerCase()} и ${MODALITY_LABEL[b.modality].toLowerCase()}. ` +
      `Но знак Солнца — это один параметр из многих: две пары с одинаковыми знаками живут совершенно по-разному, ` +
      `потому что различает их всё остальное, а не месяц рождения.`,
  });

  items.push({
    q: `Сколько процентов совместимости у ${pair}?`,
    a:
      `Наш справочный балл для этой пары — ${score.total} из 90 возможных. Он складывается из четырёх частей: ` +
      score.parts.map((p) => `${p.label.toLowerCase()} ${p.value} из ${p.max}`).join(", ") +
      `. Важная оговорка: процентов совместимости в самой астрологической традиции не существует — это наша арифметика ` +
      `поверх классических правил, и мы показываем её целиком именно поэтому. Считать такое число приговором нельзя, ` +
      `оно описывает сочетание знаков, а не двух конкретных людей.`,
  });

  // Ответ намеренно не повторяет текст блока «Аспект между знаками»: разбор
  // аспекта уже стоит на странице выше, и дословный повтор давал один и тот же
  // абзац трижды на одном документе.
  items.push({
    q: same
      ? `Что означает соединение — когда у обоих один знак?`
      : `Какой аспект между ${a.genitive} и ${b.genitive}?`,
    a: same
      ? `Когда партнёры родились под одним знаком, расстояние между знаками равно нулю — это соединение. ` +
        `Оба ${a.name}: ${a.dateRange}, стихия ${ELEMENT_LABEL[a.element]}, крест ${MODALITY_LABEL[a.modality].toLowerCase()}, управитель ${a.ruler}. ` +
        `Практический вывод один: всё, что сказано про сильную сторону знака, и всё, что сказано про теневую, ` +
        `в такой паре удваивается — компенсировать перекос некому.`
      : `Между ${a.genitive} (${a.dateRange}) и ${b.genitive} (${b.dateRange}) ровно ${aspect.angle} по кругу зодиака — ` +
        `аспект «${aspect.name}». Считается он просто: знаки идут по кругу подряд, и достаточно посчитать, сколько их между двумя. ` +
        `У этой пары ${a.element === b.element ? `стихия общая — ${ELEMENT_LABEL[a.element]}` : `стихии разные: ${ELEMENT_LABEL[a.element]} и ${ELEMENT_LABEL[b.element]}`}, ` +
        `${a.modality === b.modality ? `а крест совпадает — ${MODALITY_LABEL[a.modality].toLowerCase()}` : `кресты тоже разные: ${MODALITY_LABEL[a.modality].toLowerCase()} и ${MODALITY_LABEL[b.modality].toLowerCase()}`}. ` +
        `Разбор самого аспекта — выше на этой странице.`,
  });

  items.push({
    q: `Кто в паре ${pair} уступает первым?`,
    a:
      (polarity(a) !== polarity(b)
        ? `Полярности у знаков разные: ${a.name} — ${polarity(a)}, ${b.name} — ${polarity(b)}. Традиция считает, что активный знак чаще предлагает и настаивает, воспринимающий — чаще принимает и подстраивается. К полу человека это отношения не имеет, речь о способе действовать. `
        : `Полярность у обоих одна — ${polarity(a)}, то есть оба одинаково склонны ${polarity(a) === "ян" ? "предлагать и настаивать" : "выжидать и подстраиваться"}. Автоматического распределения ролей в такой паре нет. `) +
      (a.modality === b.modality
        ? `Кресты тоже совпадают, а значит уступать никто не привык: договариваться придётся явно, а не по умолчанию.`
        : `Зато кресты разные, и роли обычно делятся по ним: один запускает, второй удерживает или подстраивает.`),
  });

  if (!same) {
    items.push({
      q: `${a.name} и ${b.name}: стоит ли им вступать в брак?`,
      a:
        `Астрология на такой вопрос не отвечает и отвечать не должна — она описывает склад характера, а решение принимают двое. ` +
        `Что можно сказать по знакам: сильная сторона ${a.genitive} — ${a.strength}, у ${b.genitive} — ${b.strength}. ` +
        `Проверять стоит другое: ${a.shadow} у одного и ${b.shadow} у другого. Пары расходятся не из-за несовместимых знаков, ` +
        `а из-за теневых черт, которые не проговорили заранее.`,
    });
  }

  return items;
}
