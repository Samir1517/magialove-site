/** Гармония линий по Ра Уру Ху: зеркальные позиции на «этажах» гексаграммы. */
const HARMONY: Record<LineNumber, LineNumber> = { 1: 4, 4: 1, 2: 5, 5: 2, 3: 6, 6: 3 };

export type ProfileVerdict = "resonance" | "shared" | "harmony" | "dissonance";

export interface ProfileLinesResult {
  a: LineNumber[];
  b: LineNumber[];
  /** Линии, которые есть у обоих. */
  shared: LineNumber[];
  /** Пары «линия одного — гармоничная ей линия другого». */
  harmonies: { from: LineNumber; to: LineNumber }[];
  verdict: ProfileVerdict;
}

function parseProfile(profile: string): LineNumber[] {
  return profile
    .split("/")
    .map((n) => Number(n.trim()))
    .filter((n): n is LineNumber => n >= 1 && n <= 6);
}

export function calcProfileLines(profileA: string, profileB: string): ProfileLinesResult | null {
  const a = parseProfile(profileA);
  const b = parseProfile(profileB);
  if (a.length !== 2 || b.length !== 2) return null;

  const shared = a.filter((line) => b.includes(line));
  const harmonies: { from: LineNumber; to: LineNumber }[] = [];
  for (const la of a) {
    for (const lb of b) {
      // Гармоничную пару засчитываем один раз: 1↔4 и 4↔1 — одно и то же.
      if (HARMONY[la] === lb && !harmonies.some((h) => h.from === lb && h.to === la)) {
        harmonies.push({ from: la, to: lb });
      }
    }
  }

  const identical = a[0] === b[0] && a[1] === b[1];
  const verdict: ProfileVerdict = identical
    ? "resonance"
    : shared.length > 0
      ? "shared"
      : harmonies.length > 0
        ? "harmony"
        : "dissonance";

  return { a, b, shared, harmonies, verdict };
}

