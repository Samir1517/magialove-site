const ZONE_KEYS: ZoneKey[] = ["love", "money", "kids", "purpose", "center"];

/**
 * Короткие имена зон для карточек. Полные названия («Линия детей и творчества»)
 * в карточку не помещаются, а знаки «+ · − · ·» без подписей нечитаемы: чтобы
 * их понять, надо помнить порядок пяти зон, чего никто делать не будет.
 */
const ZONE_SHORT: Record<ZoneKey, string> = {
  love: "любовь",
  money: "деньги",
  kids: "дети",
  purpose: "предназначение",
  center: "комфорт",
};

/** Словесная сводка: где аркан гармоничен и где напряжён. */
function zoneSummary(n: number): string {
  const harmonic = ZONE_KEYS.filter((z) => zoneCharacter(z, n) === "harmonic").map((z) => ZONE_SHORT[z]);
  const tense = ZONE_KEYS.filter((z) => zoneCharacter(z, n) === "tense").map((z) => ZONE_SHORT[z]);
  const parts: string[] = [];
  if (harmonic.length) parts.push(`Гармоничен: ${harmonic.join(", ")}`);
  if (tense.length) parts.push(`Напряжён: ${tense.join(", ")}`);
  if (!parts.length) return "Формула не относит его ни к гармоничным, ни к напряжённым ни в одной зоне";
  return parts.join(" · ");
}

